fmt_dollar <- function(x, digits = 2) {
  base::paste0("$", base::formatC(base::as.numeric(x), format = "f", digits = digits, big.mark = ","))
}
fmt_pct <- function(x, digits = 1) {
  base::paste0(base::formatC(base::as.numeric(x) * 100, format = "f", digits = digits), "%")
}
format_ref_list <- function(nums) {
  nums <- base::sort(base::unique(base::as.integer(nums)))
  run_id <- base::cumsum(base::c(1L, base::diff(nums) != 1L))
  runs <- base::split(nums, run_id)
  parts <- base::vapply(runs, function(r) {
    if (base::length(r) >= 3L) base::sprintf("%d-%d", r[[1]], r[[base::length(r)]])
    else base::paste(r, collapse = ", ")
  }, character(1))
  base::paste0("References: ", base::paste(parts, collapse = ", "), ".")
}

