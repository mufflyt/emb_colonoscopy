#!/usr/bin/env Rscript
#' Manuscript slide deck
#'
#' Assembles a PowerPoint summary of the study from the already-committed
#' manuscript tables (tables/manuscript_table*.csv, tables/*.csv) and figures
#' (figures/figure*.jpeg|png). Unlike analysis/07_manuscript_outputs.R, this
#' script does not recompute the model -- it packages the current committed
#' outputs, so re-run analysis/07_manuscript_outputs.R (and the figure
#' scripts) first if the underlying numbers have changed. The manuscript is
#' blinded for double-anonymized review (see manuscript/manuscript.qmd's
#' header comment); this deck follows the same convention and carries no
#' author/institution names.
#'
#' All on-slide text spells out terms in full (no "endometrial biopsy"/"EMB",
#' "dilation and curettage"/"D&C", "Centers for Medicare & Medicaid
#' Services"/"CMS", etc. abbreviations). Every content slide carries: (1) a
#' small numbered-reference footer naming exactly which manuscript reference
#' numbers its content draws on, and (2) a speaker-notes talking-point
#' script. The reference numbering and full reference list are copied
#' directly from manuscript/manuscript.qmd's numbered References section (as
#' last corrected 2026-09-12 -- see that file's own header comment for the
#' citation-numbering audit history); re-copy `references` below and the
#' per-slide `refs =` numbers if that section is renumbered again.
#'
#' NOTE: the embedded chart images (figures/figure*.jpeg|png) are the
#' manuscript's own published figures, generated by other analysis/ scripts
#' (01-05, 09-10). Their axis labels and legends still use the short strategy
#' names ("EMB", "D&C") baked in at render time; relabeling them in full
#' would mean editing those figure-generation scripts, which was out of
#' scope here since it would change the manuscript's actual published
#' figures, not just this slide deck.
#'
#' Run from the repository root:
#'   Rscript analysis/18_manuscript_slides.R
#'
#' Produces manuscript/manuscript_slides.pptx.

