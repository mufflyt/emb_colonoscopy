  pptx <- officer::ph_with(pptx, value = ft, location = officer::ph_location(left = 0.4, top = top, width = 9.2, height = 5.0))
  if (!base::is.null(notes)) pptx <- add_notes(pptx, notes)
  pptx <- add_ref_footer(pptx, refs)
  pptx
}

