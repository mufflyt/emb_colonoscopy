# ---- flextable styling helper --------------------------------------------

style_ft <- function(ft, font_size = 14) {
  ft %>%
    flextable::fontsize(size = font_size, part = "all") %>%
    flextable::bold(part = "header") %>%
    flextable::bg(bg = "#1F3864", part = "header") %>%
    flextable::color(color = "white", part = "header") %>%
    flextable::autofit()
}

pptx <- officer::read_pptx()

add_notes <- function(pptx, notes) {
  officer::set_notes(pptx, value = notes, location = officer::notes_location_type())
}

add_ref_footer <- function(pptx, refs, top = 7.05) {
  if (base::is.null(refs) || base::length(refs) == 0L) return(pptx)
  txt <- format_ref_list(refs)
  officer::ph_with(
    pptx,
    value = officer::fpar(officer::ftext(txt, prop = officer::fp_text(font.size = 9, italic = TRUE, color = "#595959"))),
    location = officer::ph_location(left = 0.4, top = top, width = 9.2, height = 0.3)
  )
}

add_title_slide <- function(pptx, title, subtitle, notes = NULL) {
  pptx <- officer::add_slide(pptx, layout = "Title Slide", master = "Office Theme")
  pptx <- officer::ph_with(pptx, value = title, location = officer::ph_location_type(type = "ctrTitle"))
  pptx <- officer::ph_with(pptx, value = subtitle, location = officer::ph_location_type(type = "subTitle"))
  if (!base::is.null(notes)) pptx <- add_notes(pptx, notes)
  pptx
}

add_bullets_slide <- function(pptx, title, bullets, font_size = 20, notes = NULL, refs = NULL) {
  pptx <- officer::add_slide(pptx, layout = "Title and Content", master = "Office Theme")
  pptx <- officer::ph_with(pptx, value = title, location = officer::ph_location_type(type = "title"))
  fpar_list <- base::lapply(bullets, function(b) {
    officer::fpar(officer::ftext(b, prop = officer::fp_text(font.size = font_size)))
  })
  block <- base::do.call(officer::block_list, fpar_list)
  pptx <- officer::ph_with(pptx, value = block, location = officer::ph_location_type(type = "body"))
  if (!base::is.null(notes)) pptx <- add_notes(pptx, notes)
  pptx <- add_ref_footer(pptx, refs)
  pptx
}

add_image_slide <- function(pptx, title, image_path, caption = NULL, notes = NULL, refs = NULL) {
  pptx <- officer::add_slide(pptx, layout = "Title Only", master = "Office Theme")
  pptx <- officer::ph_with(pptx, value = title, location = officer::ph_location_type(type = "title"))
  dims <- magick::image_info(magick::image_read(image_path))
  max_w <- 9.0
  max_h <- 4.9
  scale <- base::min(max_w / dims$width, max_h / dims$height)
  w <- dims$width * scale
  h <- dims$height * scale
  left <- (10 - w) / 2
  top <- 1.5
  pptx <- officer::ph_with(
    pptx, value = officer::external_img(image_path, width = w, height = h),
    location = officer::ph_location(left = left, top = top, width = w, height = h)
  )
  if (!base::is.null(caption)) {
    pptx <- officer::ph_with(
      pptx, value = caption,
      location = officer::ph_location(left = 0.5, top = top + h + 0.1, width = 9, height = 0.5)
    )
  }
  if (!base::is.null(notes)) pptx <- add_notes(pptx, notes)
  pptx <- add_ref_footer(pptx, refs)
  pptx
}

add_two_image_slide <- function(pptx, title, image_paths, captions = NULL, notes = NULL, refs = NULL) {
  pptx <- officer::add_slide(pptx, layout = "Title Only", master = "Office Theme")
  pptx <- officer::ph_with(pptx, value = title, location = officer::ph_location_type(type = "title"))
  max_w <- 4.5
  max_h <- 4.3
  lefts <- base::c(0.35, 5.15)
  for (i in base::seq_along(image_paths)) {
    dims <- magick::image_info(magick::image_read(image_paths[[i]]))
    scale <- base::min(max_w / dims$width, max_h / dims$height)
    w <- dims$width * scale
    h <- dims$height * scale
    top <- 1.5
    pptx <- officer::ph_with(
      pptx, value = officer::external_img(image_paths[[i]], width = w, height = h),
      location = officer::ph_location(left = lefts[[i]] + (max_w - w) / 2, top = top, width = w, height = h)
    )
    if (!base::is.null(captions)) {
      pptx <- officer::ph_with(
        pptx, value = captions[[i]],
        location = officer::ph_location(left = lefts[[i]], top = top + max_h + 0.05, width = max_w, height = 0.55)
      )
    }
  }
  if (!base::is.null(notes)) pptx <- add_notes(pptx, notes)
  pptx <- add_ref_footer(pptx, refs)
  pptx
}

add_table_slide <- function(pptx, title, ft, top = 1.5, notes = NULL, refs = NULL) {
  pptx <- officer::add_slide(pptx, layout = "Title Only", master = "Office Theme")
